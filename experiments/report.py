class Bank:
    """Queryable index over loaded rows -- every table selects through this."""

    def __init__(self, rows: list[Row]) -> None:
        self.rows = rows

    def select(self, **kw: Any) -> list[Row]:
        """Rows matching every keyword exactly (``None`` matches a null field)."""
        out = []
        for r in self.rows:
            if all(getattr(r, k, "\0") == v for k, v in kw.items()):
                out.append(r)
        return out

    def f1(self, **kw: Any) -> list[float]:
        return [float(r.macro_f1) for r in self.select(**kw) if _finite(r.macro_f1)]

    def by_seed(self, **kw: Any) -> dict[int, float]:
        return {r.seed: float(r.macro_f1) for r in self.select(**kw) if _finite(r.macro_f1)}

    def blocks(self) -> set[str]:
        return {r.block for r in self.rows}

    def records(self, blocks: tuple[str, ...] | None = None) -> list[A.Record]:
        """:class:`experiments.analyze.Record` view for the statistical battery.

        Restricted to ``blocks`` on purpose: the battery pairs on (arm, model,
        attack), so pooling Tier-1 with the Tier-2 sweeps would silently mix
        different alpha / sigma / attack-fraction settings into one cell.
        """
        return [
            A.Record(run_id=r.run_id, arm=r.arm, model=r.model, seed=r.seed,
                     block=r.block, attack=r.attack, alpha=r.alpha, sigma=r.sigma,
                     macro_f1=r.macro_f1, acc=r.acc,
                     energy_ratio=(r.energy or {}).get("ratio"), correct=r.correct)
            for r in self.rows if blocks is None or r.block in blocks
        ]


