def _jsonable(obj: Any) -> Any:
    if isinstance(obj, StatRow):
        return {k: _jsonable(v) for k, v in obj.__dict__.items()}
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return None if not math.isfinite(float(obj)) else float(obj)
    if isinstance(obj, float):
        return None if not math.isfinite(obj) else obj
    if isinstance(obj, np.ndarray):
        return _jsonable(obj.tolist())
    return obj


def _block_inventory(bank: Bank) -> dict[str, dict[str, Any]]:
    """Per-block run census: what the battery table has to say, from the runs.

    ``n_runs`` is files on disk that parsed; ``n_distinct_configs`` deduplicates
    semantically (the T3tau manifest emitted several cells in triplicate and the
    X3 batteries re-ran shared seeds under fresh run_ids; ``config_hash`` is
    stale in the expansion manifests, so it cannot key this);
    ``n_diverged`` counts runs whose macro-F1 is a divergence placeholder, which
    every table shows as ``div.`` and no mean includes.
    """
    out: dict[str, dict[str, Any]] = {}
    for block in sorted(bank.blocks()):
        rows = [r for r in bank.rows if r.block == block]
        out[block] = {
            "n_runs": len(rows),
            "n_distinct_configs": len({_sem_key(r) for r in rows}),
            "n_diverged": sum(1 for r in rows if r.diverged),
            "models": sorted({r.model for r in rows}),
            "arms": sorted({r.arm for r in rows}),
            "seeds": sorted({r.seed for r in rows}),
            "attacks": sorted({r.attack or "clean" for r in rows}),
            "n_with_ldp": sum(1 for r in rows if r.sigma is not None),
            "taus": sorted({r.tau for r in rows if r.tau is not None}),
            "sigmas": sorted({r.sigma for r in rows if r.sigma is not None}),
        }
    return out


def summary_payload(bank: Bank, feds: list[dict[str, Any]], stats: dict[str, Any],
                    tables: dict[str, str]) -> dict[str, Any]:
    """The machine-readable mirror of everything the tables say."""
    coverage: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in bank.rows:
        coverage[r.block][f"{r.arm}|{r.model}|{r.attack or 'clean'}"] += 1
    todo_counts = {name: text.count("\\TODOnum") for name, text in sorted(tables.items())}
    inventory = _block_inventory(bank)
    with_block = sum(v["n_runs"] for b, v in inventory.items() if b != "?")
    return {
        "meta": {
            "n_runs": len(bank.rows),
            "n_runs_with_block": with_block,
            "blocks": sorted(bank.blocks()),
            "n_federations": len(feds),
            "planned_seeds": PLANNED_SEEDS,
            "rounds_target_fraction": ROUNDS_TARGET_FRACTION,
            "tost_margin": TOST_MARGIN,
            "generator": "experiments.report",
        },
        "coverage": {b: dict(sorted(c.items())) for b, c in sorted(coverage.items())},
        "block_inventory": inventory,
        "per_arm": stats["analyze"]["per_arm"],
        "pairwise_wilcoxon_holm": stats["analyze"]["pairwise_wilcoxon_holm"],
        "mcnemar_parity": stats["analyze"]["mcnemar_parity"],
        "hypotheses": {
            "h1a": _jsonable(stats["h1a"]), "h1b": _jsonable(stats["h1b"]),
            "h2_wilcoxon": _jsonable(stats["h2_wilcoxon"]),
            "h2_friedman": _jsonable(stats["h2_friedman"]),
            "h3": _jsonable(stats["h3"]), "h4": _jsonable(stats["h4"]),
            "h5": _jsonable(stats["h5"]),
            "verdicts": {k: {"evidence": e, "supported": s}
                         for k, (e, s) in _verdicts(stats).items()},
        },
        "tables": {"todo_markers": todo_counts,
                   "todo_total": sum(todo_counts.values())},
    }


def write_report(runs_dir: Path | str | Sequence[Path | str],
                 tables_dir: Path | str,
                 data_dir: Path | str | None = None, resamples: int = 10000,
                 summary_path: Path | str | None = None) -> dict[str, Any]:
    """Load, analyse, write every table and ``summary.json``; return the summary.

    ``runs_dir`` is either one directory or a list of directories in increasing
    precedence (``CORPUS_DIRS``): a multi-directory load merges the batteries
    with the documented run_id then semantic deduplication of
    :func:`load_corpus`.
    """
    if isinstance(runs_dir, (list, tuple)):
        rows = load_corpus(list(runs_dir))
        first_dir = Path(runs_dir[0])
    else:
        rows = load_rows(runs_dir)
        first_dir = Path(runs_dir)
    bank = Bank(rows)
    feds = load_federations(data_dir) if data_dir else []
    stats = statistical_battery(bank, resamples)
    tables = build_all_tables(bank, feds, stats, resamples,
                              Path(data_dir) if data_dir else None)
    out_dir = Path(tables_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in tables.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    summary = summary_payload(bank, feds, stats, tables)
    target = Path(summary_path) if summary_path else first_dir / "summary.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(_jsonable(summary), indent=2, sort_keys=True),
                      encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        prog="python -m experiments.report",
        description="Generate the manuscript's generated tables from a runs/ directory.")
    p.add_argument("--runs-dir", type=Path, nargs="+", default=[Path("runs")],
                   help="run directories in increasing precedence: on a run_id "
                        "or semantic collision the later directory's copy wins "
                        "(paper corpus: runs_snn_fixed runs runs_x3 "
                        "runs_ssm_x3 runs_gap_x3)")
    p.add_argument("--tables-dir", type=Path, default=Path("paper/tables"))
    p.add_argument("--data-dir", type=Path, default=Path("data_battery"),
                   help="staged federations (dataset + non-convergence tables)")
    p.add_argument("--summary", type=Path, default=None,
                   help="summary.json path (default: <first runs-dir>/summary.json)")
    p.add_argument("--resamples", type=int, default=10000, help="BCa bootstrap resamples")
    args = p.parse_args(argv)

    runs_dirs = args.runs_dir if isinstance(args.runs_dir, list) else [args.runs_dir]
    summary = write_report(runs_dirs, args.tables_dir, args.data_dir,
                           args.resamples, args.summary)
    meta = summary["meta"]
    print(f"loaded {meta['n_runs']} runs from {' '.join(str(d) for d in runs_dirs)} "
          f"(blocks {', '.join(meta['blocks']) or 'none'}), "
          f"{meta['n_federations']} staged federations")
    print(f"wrote {len(summary['tables']['todo_markers'])} tables -> {args.tables_dir}")
    for name, n in summary["tables"]["todo_markers"].items():
        print(f"  {name:<34} {n:>4} TODOnum")
    print(f"  {'TOTAL':<34} {summary['tables']['todo_total']:>4} TODOnum")
    verdicts = summary["hypotheses"]["verdicts"]
    decided = [k for k, v in verdicts.items() if v["supported"] is not None]
    print(f"hypothesis verdicts decidable from this data: "
          f"{', '.join(decided) if decided else 'none'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
