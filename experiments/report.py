@dataclass
class StatRow:
    """One filled row of ``tab_stats``, and the evidence one hypothesis rests on."""

    family: str
    comparison: str
    test: str
    statistic: float | None = None
    p: float | None = None
    p_holm: float | None = None
    effect: float | None = None
    band: str | None = None
    ci: tuple[float, float] | None = None
    n: int | None = None
    supported: bool | None = None
    note: str = ""


def _worst(rows: list[StatRow]) -> StatRow | None:
    """The least-favourable member of a family (largest Holm-adjusted p).

    Conservative on purpose: a family whose decision rule is a conjunction over
    cells is only as strong as its weakest cell, so summarising by the weakest
    one cannot flatter the result. Every cell is in ``summary.json``.
    """
    usable = [r for r in rows if _finite(r.p)]
    if not usable:
        return None
    return max(usable, key=lambda r: r.p_holm if _finite(r.p_holm) else r.p)


def power_ceiling(rows: list[StatRow]) -> dict[str, Any] | None:
    """Smallest Holm-adjusted p this family *could* have produced, at its own n.

    The exact one-sided Wilcoxon signed-rank test on ``n`` paired seeds cannot
    return a p below ``2^-n`` -- that is the probability of every difference
    landing on the predicted side, the most extreme outcome the rank statistic
    has. Holm within a family of ``m`` members multiplies the smallest member's p
    by ``m``. So the family's floor is ``m * 2^-n_max``: when that already exceeds
    0.05 *no* configuration of the data could have declared a single cell
    significant, and a table of "not supported" verdicts is a statement about the
    seed budget, not about the defense. Returned so the tables can say so out
    loud rather than let the reader infer support was tested and refused.
    """
    usable = [r for r in rows if _finite(r.p) and (r.n or 0) > 0
              and r.test.startswith("Wilcoxon")]
    if not usable:
        return None
    m = len([r for r in rows if _finite(r.p)])
    n_max = max(int(r.n or 0) for r in usable)
    p_min = 2.0 ** (-n_max)
    floor = min(1.0, m * p_min)
    return {"family": usable[0].family, "m": m, "n_max": n_max, "p_min": p_min,
            "holm_floor": floor, "decidable": bool(floor < 0.05)}


def _ceiling_phrase(ceiling: dict[str, Any] | None) -> str:
    """One clause naming the floor, for the tables' power notes."""
    if not ceiling:
        return ""
    return (f"{ceiling['family']}: $m={ceiling['m']}$ members at "
            f"$n={ceiling['n_max']}$ seeds, floor "
            f"${_tex_float(ceiling['holm_floor'])}$")


def _tex_float(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".") if v >= 1e-3 else f"{v:.1e}"


def _holm_in_place(rows: list[StatRow], directional: bool = True) -> None:
    """Holm-adjust the family's decidable rows and set their support flags."""
    usable = [r for r in rows if _finite(r.p)]
    if not usable:
        return
    for row, p_adj in zip(usable, A.holm([float(r.p) for r in usable]), strict=True):
        row.p_holm = p_adj
        if directional:
            row.supported = bool(p_adj < 0.05 and (row.effect or 0.0) > 0.147)
        else:
            row.supported = bool(p_adj < 0.05)


def statistical_battery(bank: Bank, resamples: int) -> dict[str, Any]:
    """Every pre-registered test, computed through :mod:`experiments.analyze`."""
    out: dict[str, Any] = {}
    tier1 = bank.records(("t1a", "t1b"))
    out["analyze"] = A.analyze_records(tier1, n_resamples=resamples)
    out["h1a"] = _h1a(bank, resamples)
    out["h1b"] = _h1b(bank, resamples)
    out["h2_wilcoxon"] = _h2_wilcoxon(bank, resamples)
    out["h2_friedman"] = _h2_friedman(bank)
    out["h3"] = _h3(bank, resamples)
    out["h4"] = _h4(bank)
    out["h5"] = _h5(bank, resamples)
    return out


def _h1a(bank: Bank, resamples: int) -> dict[str, Any]:
    """McNemar on pooled-test discordance + the pre-registered TOST on Delta macro-F1."""
    snn = {r.seed: r for r in bank.select(block="t1a", arm="fedavg", model="snn")}
    cnn = {r.seed: r for r in bank.select(block="t1a", arm="fedavg", model="cnn_lstm")}
    seeds = sorted(set(snn) & set(cnn))
    tot_b = tot_c = 0
    per_seed = []
    for s in seeds:
        a, b = snn[s].correct, cnn[s].correct
        if not a or not b or len(a) != len(b):
            continue
        res = A.mcnemar_from_correct(a, b)
        res["seed"] = s
        per_seed.append(res)
        tot_b += int(res["b"])
        tot_c += int(res["c"])
    pooled = A.mcnemar_test(tot_b, tot_c) if per_seed else None
    diffs = [float(snn[s].macro_f1) - float(cnn[s].macro_f1) for s in seeds
             if _finite(snn[s].macro_f1) and _finite(cnn[s].macro_f1)]
    interval = bca(diffs, resamples)
    equivalent = (interval is not None
                  and abs(interval[0]) < TOST_MARGIN and abs(interval[1]) < TOST_MARGIN)
    return {"pooled": pooled, "per_seed": per_seed, "delta_macro_f1": diffs,
            "ci": interval, "equivalent": equivalent if interval else None,
            "n": len(diffs), "margin": TOST_MARGIN}


def _h1b(bank: Bank, resamples: int) -> dict[str, Any]:
    """Energy ratio rho over seeds: BCa CI upper bound < 1 is the decision rule."""
    ratios = [float(r.energy["ratio"]) for r in bank.select(block="t1a", arm="fedavg",
                                                            model="snn")
              if r.energy and _finite(r.energy.get("ratio"))]
    interval = bca(ratios, resamples)
    w = A.wilcoxon_signed_rank(np.asarray(ratios) - 1.0) if len(ratios) >= 2 else None
    return {"ratios": ratios, "ci": interval, "wilcoxon": w,
            "supported": (interval is not None and interval[1] < 1.0),
            "n": len(ratios)}


def _h2_wilcoxon(bank: Bank, resamples: int) -> list[StatRow]:
    """Each (pipeline x model x attack) cell against no-defense, Holm within family."""
    rows: list[StatRow] = []
    for arm, agg in (("pipeline_krum", "Krum"), ("pipeline_geomed", "geo-median")):
        for model in MODEL_ORDER:
            for attack in ATTACK_ORDER[1:]:
                base = bank.by_seed(block="t1b", arm="no_defense", model=model,
                                    attack=attack)
                cand = bank.by_seed(block="t1b", arm=arm, model=model, attack=attack)
                seeds = sorted(set(base) & set(cand))
                comparison = (f"pipeline+{agg} vs no defense "
                              f"({MODEL_LABEL[model]}/{_atk_label(attack)})")
                if len(seeds) < 2:
                    # Emitted anyway so the family knows its own planned size.
                    rows.append(StatRow(family="H2 defense", comparison=comparison,
                                        test="Wilcoxon + Holm", n=len(seeds),
                                        note="fewer than two paired seeds"))
                    continue
                a = np.array([cand[s] for s in seeds])
                b = np.array([base[s] for s in seeds])
                w = A.wilcoxon_signed_rank(a, b)
                eff = A.cliffs_delta(a, b)
                rows.append(StatRow(
                    family="H2 defense", comparison=comparison,
                    # One-sided per the H2 pre-registration (pipeline > no defense).
                    test="Wilcoxon + Holm", statistic=w["T_plus"],
                    p=w["p_greater"], effect=eff["delta"], band=eff["magnitude"],
                    ci=bca(list(a - b), resamples), n=len(seeds)))
    _holm_in_place(rows)
    return rows


def _friedman_over(bank: Bank, unit: str) -> dict[str, Any]:
    """Friedman over the five defense arms; ``unit`` picks the blocking scheme.

    ``"seed_mean"`` is the **pre-registered** protocol (HYPOTHESES.md, statistical
    conventions): one block per (attack x model) cell, each arm entering with its
    mean over the seeds all five arms ran. ``"seed"`` is the per-seed-row variant,
    which multiplies the block count by the seed count and so treats fifteen
    repetitions of the same cell as fifteen independent blocks --
    pseudo-replication that inflates Q and shrinks the Nemenyi critical
    difference. It is kept only as a declared sensitivity analysis.
    """
    arms = [a for _label, a in _DEFENSE_ROWS]
    blocks: list[list[float]] = []
    labels: list[str] = []
    for model in MODEL_ORDER:
        for attack in ATTACK_ORDER[1:]:
            per_arm = {a: bank.by_seed(block="t1b", arm=a, model=model, attack=attack)
                       for a in arms}
            if any(not v for v in per_arm.values()):
                continue
            common = sorted(set.intersection(*(set(v) for v in per_arm.values())))
            if not common:
                continue
            if unit == "seed":
                for seed in common:
                    blocks.append([per_arm[a][seed] for a in arms])
                    labels.append(f"{model}/{attack}/s{seed}")
            else:
                blocks.append([float(np.mean([per_arm[a][s] for s in common]))
                               for a in arms])
                labels.append(f"{model}/{attack} (mean of {len(common)} seeds)")
    if len(blocks) < 2:
        return {"available": False, "arms": arms, "n_blocks": len(blocks), "unit": unit}
    mat = np.asarray(blocks, dtype=float)
    fr = A.friedman(mat)
    cd = A.nemenyi_cd(len(arms), fr["n"])
    posthoc = A.nemenyi_posthoc(fr["avg_ranks"], fr["n"])
    keys = list(posthoc)
    for k, p_adj in zip(keys, A.holm([posthoc[k]["p"] for k in keys]), strict=True):
        posthoc[k]["p_holm"] = p_adj
    named: dict[str, dict[str, float]] = {}
    separated: list[str] = []
    for k, v in posthoc.items():
        i, j = (int(x) for x in k.split("-"))
        diff = abs(fr["avg_ranks"][i] - fr["avg_ranks"][j])
        v["rank_diff"] = float(diff)
        v["separated_by_cd"] = bool(diff > cd)
        name = f"{arms[i]}_vs_{arms[j]}"
        named[name] = v
        if diff > cd:
            separated.append(name)
    return {"available": True, "arms": arms, "blocks": labels, "unit": unit, **fr,
            "cd": cd, "posthoc": named, "separated_by_cd": separated}


def _h2_friedman(bank: Bank) -> dict[str, Any]:
    """The pre-registered Friedman (blocks = (attack x model) seed-means).

    The per-seed-row variant travels alongside it under ``"sensitivity"`` so the
    manuscript can report both without either being mistaken for the other.
    """
    primary = _friedman_over(bank, "seed_mean")
    primary["sensitivity"] = _friedman_over(bank, "seed")
    return primary


def _h3(bank: Bank, resamples: int) -> dict[str, list[StatRow]]:
    """H3a evasion (attacker score) and H3b damage (macro-F1 drop), adaptive vs sign-flip."""
    evasion: list[StatRow] = []
    damage: list[StatRow] = []
    for arm, agg in (("pipeline_krum", "Krum"), ("pipeline_geomed", "geo-median")):
        for model in MODEL_ORDER:
            scores: dict[str, dict[int, float]] = {}
            drops: dict[str, dict[int, float]] = {}
            for attack in ("adaptive_cosine", "sign_flip"):
                skip = attack == "adaptive_cosine"
                rows = bank.select(block="t1b", arm=arm, model=model, attack=attack)
                scores[attack] = {}
                drops[attack] = {}
                clean = bank.by_seed(block="t1a", arm=arm, model=model)
                for r in rows:
                    g = r.gate_stats(skip)
                    if g and _finite(g["attacker_score"]):
                        scores[attack][r.seed] = g["attacker_score"]
                    if r.seed in clean and _finite(r.macro_f1):
                        drops[attack][r.seed] = clean[r.seed] - float(r.macro_f1)
            evasion.append(_paired_row(
                "H3a evasion", f"adaptive vs sign-flip score ({agg}/{MODEL_LABEL[model]})",
                scores["sign_flip"], scores["adaptive_cosine"], resamples))
            damage.append(_paired_row(
                "H3b damage", f"adaptive vs sign-flip drop ({agg}/{MODEL_LABEL[model]})",
                drops["adaptive_cosine"], drops["sign_flip"], resamples))
    _holm_in_place(evasion)
    _holm_in_place(damage)
    return {"evasion": evasion, "damage": damage}


def _paired_row(family: str, comparison: str, high: dict[int, float],
                low: dict[int, float], resamples: int) -> StatRow:
    """Wilcoxon of ``high - low`` paired by seed (direction: high > low expected)."""
    seeds = sorted(set(high) & set(low))
    test = "Wilcoxon + Holm"  # one-sided: every caller states a direction
    if len(seeds) < 2:
        return StatRow(family=family, comparison=comparison, test=test,
                       n=len(seeds), note="fewer than two paired seeds")
    a = np.array([high[s] for s in seeds])
    b = np.array([low[s] for s in seeds])
    w = A.wilcoxon_signed_rank(a, b)
    eff = A.cliffs_delta(a, b)
    return StatRow(family=family, comparison=comparison, test=test,
                   statistic=w["T_plus"], p=w["p_greater"], effect=eff["delta"],
                   band=eff["magnitude"], ci=bca(list(a - b), resamples), n=len(seeds))


def _h4(bank: Bank) -> list[StatRow]:
    """Jonckheere-Terpstra: honest false-rejection rate increasing in sigma, per tau."""
    rows: list[StatRow] = []
    for tau in LDP_TAUS:
        groups: list[list[float]] = []
        flat_sigma: list[float] = []
        flat_frr: list[float] = []
        for sigma in LDP_SIGMAS:
            vals = []
            for r in bank.select(block="t2c", tau=tau):
                if r.sigma is None or abs(r.sigma - sigma) > 1e-9:
                    continue
                g = r.gate_stats()
                if g and _finite(g["honest_frr"]):
                    vals.append(g["honest_frr"])
                    flat_sigma.append(sigma)
                    flat_frr.append(g["honest_frr"])
            groups.append(vals)
        present = [g for g in groups if g]
        if len(present) < 3:
            rows.append(StatRow(family="H4 privacy",
                                comparison=f"FRR trend across $\\sigma$ ($\\tau={tau:g}$)",
                                test="Jonckheere--Terpstra",
                                n=sum(len(g) for g in groups),
                                note="fewer than three populated sigma levels"))
            continue
        jt = A.jonckheere(present)
        sp = A.spearman(flat_sigma, flat_frr)
        rows.append(StatRow(
            family="H4 privacy", comparison=f"FRR trend across $\\sigma$ ($\\tau={tau:g}$)",
            test="Jonckheere--Terpstra", statistic=jt["z"], p=jt["p_one_increasing"],
            effect=sp["rho"], band="Spearman", n=sum(len(g) for g in groups),
            supported=bool(jt["p_one_increasing"] < 0.05)))
    _holm_in_place(rows, directional=False)
    return rows


def _h5(bank: Bank, resamples: int) -> dict[str, list[StatRow]]:
    """H5a alpha trend (Jonckheere) and H5b differential degradation (Wilcoxon)."""
    order = [0.1, 0.5, 1.0, 100.0]
    trend: list[StatRow] = []
    for arm_label, arm in _ALPHA_ARMS:
        for model in MODEL_ORDER:
            groups = [_alpha_cell(bank, a, arm, model, None)[0] for a in order]
            present = [g for g in groups if g]
            comparison = (f"\\macroF{{}} trend across $\\alpha$ "
                          f"({arm_label}/{MODEL_LABEL[model]})")
            if len(present) < 3:
                trend.append(StatRow(family="H5a non-IID", comparison=comparison,
                                     test="Jonckheere--Terpstra",
                                     n=sum(len(g) for g in groups),
                                     note="fewer than three populated alpha levels"))
                continue
            jt = A.jonckheere(present)
            flat_a = [a for a, g in zip(order, groups, strict=True) for _ in g]
            flat_v = [v for g in groups for v in g]
            sp = A.spearman(flat_a, flat_v)
            trend.append(StatRow(
                family="H5a non-IID", comparison=comparison, test="Jonckheere--Terpstra",
                statistic=jt["z"], p=jt["p_one_increasing"], effect=sp["rho"],
                band="Spearman", n=len(flat_v),
                supported=bool(jt["p_one_increasing"] < 0.05)))
    _holm_in_place(trend, directional=False)

    differential: list[StatRow] = []
    for model in MODEL_ORDER:
        drops: dict[str, dict[int, float]] = {}
        for arm in ("fedavg", "pipeline_krum"):
            skew = _alpha_rows(bank, 0.1, arm, model)
            uniform = _alpha_rows(bank, 100.0, arm, model)
            drops[arm] = {s: uniform[s] - skew[s] for s in sorted(set(skew) & set(uniform))}
        differential.append(_paired_row(
            "H5b non-IID", f"FedAvg vs pipeline drop ({MODEL_LABEL[model]})",
            drops["fedavg"], drops["pipeline_krum"], resamples))
    _holm_in_place(differential)
    return {"trend": trend, "differential": differential}


def _alpha_rows(bank: Bank, alpha: float, arm: str, model: str) -> dict[int, float]:
    if abs(alpha - 0.5) < 1e-9:
        return bank.by_seed(block="t1a", arm=arm, model=model)
    return {r.seed: float(r.macro_f1)
            for r in bank.select(block="t2a", arm=arm, model=model, attack=None)
            if r.alpha is not None and abs(r.alpha - alpha) < 1e-9 and _finite(r.macro_f1)}


def _atk_label(attack: str | None) -> str:
    return {"sign_flip": "sign-flip", "gaussian_noise": "Gaussian",
            "label_flip": "label-flip", "adaptive_cosine": "adaptive",
            None: "clean"}.get(attack, str(attack))


