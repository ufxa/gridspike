def _paired_drop(bank: Bank, clean_kw: dict[str, Any], atk_kw: dict[str, Any]) -> list[float]:
    """Per-seed macro-F1 drop (clean - attacked) over the seeds both arms ran."""
    clean = bank.by_seed(**clean_kw)
    atk = bank.by_seed(**atk_kw)
    return [clean[s] - atk[s] for s in sorted(set(clean) & set(atk))]


def _ceiling(bank: Bank, model: str) -> float | None:
    vals = bank.f1(block="t1a", arm="centralized", model=model)
    return float(np.mean(vals)) if vals else None


def _rounds_to_target(rows: list[Row], target: float | None) -> str:
    """Mean first round reaching ``target`` validation macro-F1 across seeds."""
    if target is None:
        return todo("rounds to target")
    hits: list[int] = []
    curves = 0
    for r in rows:
        curve = r.val_curve()
        if not curve:
            continue
        curves += 1
        for i, v in enumerate(curve, start=1):
            if v >= target:
                hits.append(i)
                break
    if curves == 0:
        return NA
    if not hits:
        return "n.r."
    mark = "" if len(hits) == curves else f"$^{{{len(hits)}/{curves}}}$"
    return f"{np.mean(hits):.1f}{mark}"


def _int8_energy(synops: float, macs: float) -> dict[str, float]:
    """The INT8 rows: same counters, 8-bit per-operation constants."""
    from fedgrid.metrics.energy import E_AC_INT8_PJ, E_MAC_INT8_PJ

    snn = synops * E_AC_INT8_PJ * 1e-6
    ann = macs * E_MAC_INT8_PJ * 1e-6
    return {"snn_uJ": snn, "ann_uJ": ann, "ratio": (snn / ann) if ann > 0 else float("nan")}


def _energy_cells(rows: list[Row], precision: str) -> dict[str, float | None]:
    """Mean SynOps / spike rate / uJ / rho over the runs that carried an energy block."""
    syn = [float(r.energy["synops_per_inference"]) for r in rows
           if r.energy and _finite(r.energy.get("synops_per_inference"))]
    rate = [float(r.energy["spike_rate"]) for r in rows
            if r.energy and _finite(r.energy.get("spike_rate"))]
    macs = [float(r.energy["ann_cnn_lstm_macs"]) for r in rows
            if r.energy and _finite(r.energy.get("ann_cnn_lstm_macs"))]
    if not syn or not macs:
        return {"synops": None, "spike_rate": None, "uj": None, "ratio": None, "macs": None}
    s, m = float(np.mean(syn)), float(np.mean(macs))
    if precision == "INT8":
        e = _int8_energy(s, m)
    else:
        from fedgrid.metrics.energy import energy_uj

        e = energy_uj(s, m)
    return {"synops": s, "macs": m, "spike_rate": float(np.mean(rate)) if rate else None,
            "uj": e["snn_uJ"], "ratio": e["ratio"], "ann_uj": e["ann_uJ"]}


# --------------------------------------------------------------------------- #
# The twenty-one tables. Each returns a complete file body.
# --------------------------------------------------------------------------- #


def _table(schema: str, colspec: str, header: str, body: list[str],
           tail: str = "", size: str = "small", colsep: int = 4) -> str:
    preamble = f"\\{size}\n\\setlength{{\\tabcolsep}}{{{colsep}pt}}%\n"
    lines = [_HEADER.format(schema=schema), preamble,
             f"\\begin{{tabular}}{{@{{}}{colspec}@{{}}}}\n", "\\toprule\n",
             header + " \\\\\n", "\\midrule\n"]
    lines.extend(body)
    lines.extend(["\\bottomrule\n", "\\end{tabular}\n"])
    if tail:
        lines.append(tail)
    return "".join(lines)


def _r(*cells: str) -> str:
    return " & ".join(cells) + " \\\\\n"


