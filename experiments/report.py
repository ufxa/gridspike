@dataclass
class Row:
    """One RunResult, flattened to the axes the tables and figures index on."""

    run_id: str
    block: str
    arm: str
    model: str
    seed: int
    attack: str | None
    config_hash: str
    diverged: bool
    attack_fraction: float
    #: Byzantine update magnitude multiplier (``attack.params.scale``). Only the
    #: T4mag sweep sets it; everywhere else the attacker runs at its natural norm
    #: and the field is ``None``, which is *not* the same axis point as 1.0.
    atk_scale: float | None
    #: ``federation.split_mode``: ``"temporal"`` on the leakage-free re-run,
    #: absent (hence ``None``) on the original random-window split.
    split_mode: str | None
    alpha: float | None
    iid: bool
    sigma: float | None
    clip: float | None
    tau: float | None
    coding: str | None
    t_steps: int | None
    mu: float | None
    m: int | None
    f: int | None
    precision: str
    defense_kind: str | None
    agg: str | None
    rounds_planned: int
    macro_f1: float | None
    acc: float | None
    per_class_f1: list[float] | None
    confusion: list[list[int]] | None
    n_test: int | None
    correct: list[int] | None
    local_min: float | None
    local_max: float | None
    energy: dict[str, Any] | None
    latency: dict[str, Any] | None
    rounds: list[dict[str, Any]] = field(default_factory=list)

    # -- derived views ----------------------------------------------------- #

    @property
    def planned_seeds(self) -> int:
        return PLANNED_SEEDS.get(self.block, 5)

    @property
    def has_gate(self) -> bool:
        """True when this arm runs updates past a fidelity/PBFT admission gate."""
        return self.defense_kind in ("pipeline", "fidelity_only")

    def val_curve(self) -> list[float]:
        """Global validation macro-F1 per round (empty for the local-only arm)."""
        return [float(r["global"]["macro_f1"]) for r in self.rounds
                if isinstance(r.get("global"), dict)]

    def gate_stats(self, skip_first_round: bool = False) -> dict[str, float] | None:
        """Admission-gate behaviour measured from ``consensus.rejected``.

        ``honest_frr`` -- share of honest client-rounds the gate rejected;
        ``attacker_admission`` -- share of attacker client-rounds it let through;
        ``*_score`` -- mean realised fidelity score of each population. Arms with
        no gate reject nothing, so they read 0.00 / 1.00 by construction.
        """
        if not self.rounds:
            return None
        h_rej = h_tot = a_adm = a_tot = 0
        h_scores: list[float] = []
        a_scores: list[float] = []
        for rnd in self.rounds:
            if skip_first_round and int(rnd.get("round", 0)) <= 1:
                continue
            rejected = set(int(c) for c in rnd.get("consensus", {}).get("rejected", []))
            for c in rnd.get("clients", []):
                is_attacker = c.get("attack") is not None
                score = float(c.get("fidelity", 0.0))
                if is_attacker:
                    a_tot += 1
                    a_adm += int(int(c["cid"]) not in rejected)
                    a_scores.append(score)
                else:
                    h_tot += 1
                    h_rej += int(int(c["cid"]) in rejected)
                    h_scores.append(score)
        if h_tot == 0 and a_tot == 0:
            return None
        return {
            "honest_frr": h_rej / h_tot if h_tot else float("nan"),
            "attacker_admission": a_adm / a_tot if a_tot else float("nan"),
            "honest_score": float(np.mean(h_scores)) if h_scores else float("nan"),
            "attacker_score": float(np.mean(a_scores)) if a_scores else float("nan"),
            "n_honest": float(h_tot),
            "n_attacker": float(a_tot),
        }


def _get(d: Any, *path: str, default: Any = None) -> Any:
    cur = d
    for key in path:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(key)
    return default if cur is None else cur


def _row_from_payload(run_id: str, data: dict[str, Any]) -> Row | None:
    manifest = _get(data, "config", "manifest")
    if not isinstance(manifest, dict):
        return None  # not a battery RunResult (fleet_state.json, summary.json, ...)
    cfg = manifest.get("config") or {}
    final = data.get("final") or {}
    atk = cfg.get("attack") or {}
    dfn = cfg.get("defense") or {}
    ldp = cfg.get("ldp") or {}
    model_blk = cfg.get("model") or {}
    fed = cfg.get("federation") or {}
    strat = cfg.get("strategy") or {}
    conf = final.get("confusion")
    return Row(
        run_id=str(manifest.get("run_id", run_id)),
        block=str(manifest.get("block", "?")),
        arm=str(manifest.get("arm", data.get("method", "?"))),
        model=str(manifest.get("model", model_blk.get("name", "?"))),
        seed=int(manifest.get("seed", data.get("seed", 0))),
        attack=atk.get("type"),
        config_hash=str(manifest.get("config_hash", "")),
        # A run the engine abandoned (NaN loss / NaN fidelity under a strong
        # attack) writes `final.diverged` and a zero macro-F1 placeholder. That
        # zero is a *marker*, not a measurement: every table must show it as
        # ``div.`` and keep it out of the means.
        diverged=bool(final.get("diverged", False)),
        attack_fraction=float(atk.get("fraction", 0.0) or 0.0),
        atk_scale=(float(_get(atk, "params", "scale"))
                   if _finite(_get(atk, "params", "scale")) else None),
        split_mode=(str(fed["split_mode"]) if fed.get("split_mode") else None),
        alpha=(float(fed["alpha"]) if _finite(fed.get("alpha")) else None),
        iid=bool(fed.get("iid", False)),
        sigma=(float(ldp["sigma"]) if _finite(ldp.get("sigma")) else None),
        clip=(float(ldp["clip"]) if _finite(ldp.get("clip")) else None),
        tau=(float(dfn["threshold"]) if _finite(dfn.get("threshold")) else None),
        coding=model_blk.get("coding"),
        t_steps=(int(model_blk["t_steps"]) if _finite(model_blk.get("t_steps")) else None),
        mu=(float(strat["mu"]) if _finite(strat.get("mu")) else None),
        m=(int(dfn["m"]) if _finite(dfn.get("m")) else None),
        f=(int(dfn["f"]) if _finite(dfn.get("f")) else None),
        precision=str(cfg.get("precision", "fp32")),
        defense_kind=dfn.get("kind"),
        agg=dfn.get("agg"),
        rounds_planned=int(_get(cfg, "training", "rounds", default=0) or 0),
        macro_f1=final.get("macro_f1"),
        acc=final.get("acc"),
        per_class_f1=final.get("per_class_f1"),
        confusion=conf if isinstance(conf, list) else None,
        n_test=final.get("n_test"),
        correct=final.get("correct"),
        local_min=final.get("local_min_macro_f1"),
        local_max=final.get("local_max_macro_f1"),
        energy=data.get("energy"),
        latency=data.get("latency"),
        rounds=data.get("rounds") or [],
    )


def load_rows(runs_dir: Path | str) -> list[Row]:
    """Every parseable battery RunResult under ``runs_dir``, newest schema first."""
    rows: list[Row] = []
    for path in sorted(Path(runs_dir).glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if not isinstance(data, dict):
            continue
        row = _row_from_payload(path.stem, data)
        if row is not None:
            rows.append(row)
    return rows


#: Directories that make up the full run corpus, in *increasing* precedence
#: (docs/X3_ANALYSIS.md Part 2, P0): on a run_id collision -- and on a semantic
#: collision, where two batteries re-executed the same seeded configuration --
#: the later directory's copy wins, because the X3 batteries re-ran the shared
#: seeds (0-4 / 0-2) rather than reusing the original records.
CORPUS_DIRS: tuple[str, ...] = ("runs_snn_fixed", "runs", "runs_x3",
                                "runs_ssm_x3", "runs_gap_x3")


def _sem_key(r: Row) -> tuple[Any, ...]:
    """The configuration identity of a run, minus its outcome.

    Everything that selects a distinct battery cell, including the seed: two
    rows sharing this key are re-executions of one configuration (the T3tau
    manifest emits each extended LDP cell in exact triplicate, and the X3
    batteries re-ran shared seeds under fresh run_ids). ``config_hash`` is
    deliberately absent: in the expansion manifests it is copied from the
    seed-template line by convention, so it is stale rather than identifying.
    """
    return (r.block, r.arm, r.model, r.seed, r.attack, r.attack_fraction,
            r.atk_scale, r.split_mode, r.alpha, r.iid, r.sigma, r.clip,
            r.tau, r.coding, r.t_steps, r.mu, r.m, r.f, r.precision,
            r.defense_kind, r.agg)


def load_corpus(runs_dirs: Sequence[Path | str]) -> list[Row]:
    """The merged multi-battery corpus, deduplicated as documented in P0.

    Pass directories in increasing precedence (``CORPUS_DIRS``). Two passes:
    first one row per ``run_id`` (the re-executed shared seeds come in under
    the same identifier, so the later battery's copy replaces the earlier
    one); then one row per semantic configuration key, so re-executions that
    minted fresh run_ids -- and the T3tau triplicates -- still collapse to the
    higher-precedence copy. Unblock-labelled rows (latency probes) are never
    semantically deduplicated: their run_id is the only identity they carry.
    """
    by_id: dict[str, tuple[int, Row]] = {}
    for rank, d in enumerate(runs_dirs):
        for r in load_rows(d):
            if r.run_id not in by_id or rank > by_id[r.run_id][0]:
                by_id[r.run_id] = (rank, r)
    by_key: dict[Any, tuple[int, Row]] = {}
    for rank, r in by_id.values():
        key = _sem_key(r) if r.block != "?" else ("probe", r.run_id)
        if key not in by_key or rank > by_key[key][0]:
            by_key[key] = (rank, r)
    return [r for _rank, r in by_key.values()]


def load_federations(data_dir: Path | str) -> list[dict[str, Any]]:
    """Generator manifests of every staged federation (dataset/non-convergence)."""
    out: list[dict[str, Any]] = []
    root = Path(data_dir)
    if not root.is_dir():
        return out
    for man in sorted(root.glob("*/manifest.json")):
        try:
            out.append(json.loads(man.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            continue
    return out


