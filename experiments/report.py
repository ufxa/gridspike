"""RunResults -> the manuscript's twenty-one generated tables + ``summary.json``.

One command turns a directory of :class:`~fedgrid.metrics.runresult.RunResult`
JSONs into every generated artifact the manuscript ``\\input``s::

    python -m experiments.report --runs-dir runs

The file contract is ``paper/OPEN_QUESTIONS_PAPER.md`` §4.2: twenty-one files in
``paper/tables/``, each a complete ``tabular`` **body only** (no float, no
caption -- those live in the section files, so regeneration never touches
prose), with the schema documented in the file's first ``%%`` lines. (Sixteen
until 2026-07-30, when ``tab_tau_sweep`` and ``tab_ldp_tau_extended`` gave the
540-run ``t3tau`` block -- 41% of the battery -- its first reader; twenty-one
on 2026-07-31, when round 3 landed the leakage-free ``*_temporal`` re-run of
the whole Tier-1 grid and the ``t4mag`` attacker-magnitude sweep.)

**The cardinal rule: no fabricated numbers.** A cell the loaded runs cannot
support renders ``\\TODOnum{...}`` -- a loud red marker in the PDF -- never a
plausible-looking value and never a silent zero. A cell that is *structurally*
not applicable (a spiking-only column on the reference model, an admission gate
in an arm that has none) renders ``--``. Cells computed from fewer seeds than
the block plans carry a superscript with the realised ``n``; those superscripts
vanish by themselves once every cell is complete.

Statistics are **not reimplemented here**: every test comes from
:mod:`experiments.analyze` (Wilcoxon+Holm, Friedman+Nemenyi, Cliff's delta, BCa
bootstrap, McNemar, Jonckheere-Terpstra, Spearman).

Owner: results pipeline (phase 5). Companion: :mod:`experiments.figures`.
"""

