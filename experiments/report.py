# 15-17. Round 3: the leakage-free frame and the attacker-magnitude sweep.
#
# Every table above reads a battery whose windows were split at random, so a
# client's training and test windows can straddle the same event: the reviewers
# asked what the numbers are without that leakage. Blocks ``t1a_temporal`` and
# ``t1b_temporal`` re-run the whole Tier-1 grid with `federation.split_mode =
# "temporal"` -- each client's windows cut chronologically, train strictly before
# test -- at the same alpha, the same seeds and the same arms, so every cell has
# a matched twin in T1a/T1b and the difference is the split and nothing else.
#
# ``t4mag`` answers the other half: the adaptive-cosine attacker aims *inside*
# the honest cone, so the fidelity gate cannot see it by direction. What is left
# is magnitude, and T4mag sweeps it (scale in {1,2,5,10}) to find where plain
# averaging breaks and whether the gate notices.
# --------------------------------------------------------------------------- #


def _split_pair(bank: Bank, rand_block: str, temp_block: str,
                **kw: Any) -> tuple[list[float], list[float]]:
    """The same cell's macro-F1 under the random and the temporal split."""
    return (bank.f1(block=rand_block, **kw), bank.f1(block=temp_block, **kw))


def _delta(rand: list[float], temp: list[float], nd: int = 3,
           tag: str = "") -> str:
    """``temporal - random``, as the difference of the two *printed* means.

    Not a per-seed paired difference: the two blocks share seed indices, but a
    seed indexes the federation draw and the initialisation, not a matched pair
    of test windows -- the temporal split re-cuts every client's data, so there
    is no common test set to pair on. Taking the column difference also means
    the arithmetic reconciles on the page, which is the first thing a reader
    checks. Where the two cells rest on different seed counts the shorter one
    carries its realised-n superscript.

    A difference that rounds to zero prints *unsigned*: at three decimals it is
    zero, and ``-0.000`` reads as a typesetting fault rather than as a direction.
    """
    if not rand or not temp:
        return todo(tag)
    return _signed_or_zero(float(np.mean(temp)) - float(np.mean(rand)), nd)


def _signed_or_zero(v: float, nd: int) -> str:
    """``+x`` / ``-x`` at ``nd`` decimals, but a value rounding to zero unsigned."""
    if abs(round(v, nd)) == 0.0:
        return f"{0.0:.{nd}f}"
    return _signs(f"{v:+.{nd}f}")


def _delta_pct(rand: list[float], temp: list[float], tag: str = "") -> str:
    """The same difference relative to the random-split mean, in percent."""
    if not rand or not temp:
        return todo(tag)
    base = float(np.mean(rand))
    if base <= 0.0:
        return NA
    return _signed_or_zero(100.0 * (float(np.mean(temp)) - base) / base, 1)


