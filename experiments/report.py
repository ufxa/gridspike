def tab_dataset(feds: list[dict[str, Any]], data_dir: Path | None) -> str:
    schema = "one row per client + total (reference federation k=10, alpha=0.5, seed=0)"
    colspec = "l l r r l r r"
    header = (r"Client & Feeder & PV (\%) & Windows & Train/Val/Test & "
              r"\cls{normal} (\%) & Classes")
    ref = next((f for f in feds
                if _get(f, "config", "alpha") == 0.5 and _get(f, "config", "seed") == 0), None)
    body: list[str] = []
    if ref is None:
        for cid in range(10):
            body.append(_r(str(cid), *[todo(f"client {cid}")] * 6))
        body.append("\\midrule\n")
        body.append(_r("All", "5 feeders", NA, todo("windows"), todo("split"),
                       todo("normal share"), "8"))
        return _table(schema, colspec, header, body)

    hists = ref.get("label_histogram") or []
    tot_w = tot_tr = tot_va = tot_te = 0
    tot_normal = 0
    tot_all = 0
    for cid, c in enumerate(ref.get("clients", [])):
        feeder = FEEDER_LABEL.get(_get(c, "feeder", "name", default=""), todo("feeder"))
        pv = _get(c, "feeder", "pv_penetration")
        nw = c.get("n_windows")
        split = _split_counts(data_dir, ref, cid, nw)
        hist = hists[cid] if cid < len(hists) else None
        if hist:
            n_tot = int(sum(hist))
            share = hist[0] / n_tot if n_tot else None
            classes = str(sum(1 for v in hist if v > 0))
            tot_normal += int(hist[0])
            tot_all += n_tot
        else:
            share, classes = None, todo("classes")
        if split is not None:
            tr, va, te = split
            tot_tr, tot_va, tot_te = tot_tr + tr, tot_va + va, tot_te + te
            split_cell = f"{tr}/{va}/{te}"
        else:
            split_cell = todo(f"split c{cid}")
        tot_w += int(nw or 0)
        body.append(_r(str(cid), feeder, pct(pv, 0, f"pv c{cid}"),
                       thousands(nw, f"windows c{cid}"), split_cell,
                       pct(share, 2, f"normal c{cid}"), classes))
    body.append("\\midrule\n")
    all_split = (f"{tot_tr}/{tot_va}/{tot_te}" if tot_tr else todo("split total"))
    all_share = (tot_normal / tot_all) if tot_all else ref.get("normal_share")
    body.append(_r("All", "5 feeders", NA, thousands(tot_w or ref.get("total_windows")),
                   all_split, pct(all_share, 2, "normal share"), "8"))
    return _table(schema, colspec, header, body)


def _split_counts(data_dir: Path | None, ref: dict[str, Any], cid: int,
                  n_windows: Any) -> tuple[int, int, int] | None:
    """Exact split sizes, read from the client's ``.npz`` when it is on disk."""
    if data_dir is not None:
        fed_dirs = [p for p in Path(data_dir).glob("*/manifest.json")]
        for man in fed_dirs:
            try:
                if json.loads(man.read_text(encoding="utf-8")).get("config") != ref.get("config"):
                    continue
            except (OSError, ValueError):
                continue
            npz = man.parent / f"client_{cid:02d}.npz"
            if npz.exists():
                try:
                    with np.load(npz) as z:
                        return (int(z["train_idx"].size), int(z["val_idx"].size),
                                int(z["test_idx"].size))
                except (OSError, ValueError, KeyError):
                    return None
    return None


