#: Render the descriptive tag inside each ``\TODOnum``. Off by default and off in
#: the manuscript: a tag typesets as text, and in a nine-column table that alone
#: overflows the page. The stubs use the bare marker for the same reason, and
#: ``runs/summary.json`` carries the machine-readable inventory of what is
#: missing. Flip it on when debugging which cell a marker belongs to.
TODO_TAGS: bool = False


def todo(tag: str = "") -> str:
    """A loud red results-shaped hole. ``tag`` is sanitised for text mode."""
    if not TODO_TAGS:
        return "\\TODOnum{}"
    clean = re.sub(r"[^A-Za-z0-9 .,/=<>+\-]", " ", str(tag)).strip()
    clean = re.sub(r"\s+", " ", clean)[:38]
    return "\\TODOnum{" + clean + "}"


NA = "--"

#: A cell whose only runs diverged: the engine wrote a zero macro-F1 placeholder
#: rather than a measurement, so the cell shows the divergence instead of the 0.
DIV = "div."


def _finite(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(float(x))


def _signs(text: str) -> str:
    """Typeset every leading ``-``/``+`` as a real math sign, not a text hyphen."""
    return re.sub(r"(?<![\dA-Za-z$])([-+])(?=[.\d])", lambda m: f"${m.group(1)}$", text)


def fnum(x: float | None, nd: int = 3, tag: str = "") -> str:
    """Fixed-decimal number, or a TODO marker when the value is missing."""
    return _signs(f"{float(x):.{nd}f}") if _finite(x) else todo(tag)


def sig(x: float | None, nd: int = 3, tag: str = "") -> str:
    """``nd`` significant figures; scientific below 1e-2 so ratios stay readable."""
    if not _finite(x):
        return todo(tag)
    v = float(x)
    if v == 0.0:
        return "0"
    if abs(v) < 1e-2 or abs(v) >= 1e5:
        mant, exp = f"{v:.{nd - 1}e}".split("e")
        return f"${mant}\\times10^{{{int(exp)}}}$"
    return _signs(f"{v:.{max(0, nd - 1 - int(math.floor(math.log10(abs(v)))))}f}")


def thousands(x: float | None, tag: str = "") -> str:
    """Integer with LaTeX thin-space grouping (``68\\,174``)."""
    if not _finite(x):
        return todo(tag)
    return f"{int(round(float(x))):,}".replace(",", "\\,")


def pct(x: float | None, nd: int = 1, tag: str = "") -> str:
    """A fraction rendered as a percentage number (the header carries the %)."""
    return f"{100.0 * float(x):.{nd}f}" if _finite(x) else todo(tag)


def _n_mark(n: int, planned: int) -> str:
    """Superscript realised n, but only while it is short of the plan."""
    return "" if n >= planned or n <= 0 else f"$^{{{n}}}$"


def mean_sd(vals: list[float], nd: int = 3, planned: int = 5, tag: str = "") -> str:
    """``mean $\\pm$ sd`` over seeds with the short-n superscript, or a TODO."""
    v = [float(x) for x in vals if _finite(x)]
    if not v:
        return todo(tag)
    mark = _n_mark(len(v), planned)
    if len(v) == 1:
        return _signs(f"{v[0]:.{nd}f}") + mark
    return (_signs(f"{np.mean(v):.{nd}f}")
            + f"\\,$\\pm$\\,{np.std(v, ddof=1):.{nd}f}{mark}")


def mean_only(vals: list[float], nd: int = 3, planned: int = 5, tag: str = "") -> str:
    v = [float(x) for x in vals if _finite(x)]
    if not v:
        return todo(tag)
    return _signs(f"{np.mean(v):.{nd}f}") + _n_mark(len(v), planned)


def ci_str(lo: float | None, hi: float | None, nd: int = 3, tag: str = "") -> str:
    if not (_finite(lo) and _finite(hi)):
        return todo(tag)
    return _signs(f"[{float(lo):.{nd}f},\\,{float(hi):.{nd}f}]")


def bca(vals: list[float], resamples: int, seed: int = 0) -> tuple[float, float] | None:
    """BCa 95% CI over seeds (:func:`experiments.analyze.bca_ci`); ``None`` if n<2."""
    v = [float(x) for x in vals if _finite(x)]
    if len(v) < 2:
        return None
    return A.bca_ci(np.asarray(v), np.mean, n_resamples=resamples, seed=seed)


def _p(x: float | None, tag: str = "") -> str:
    """p-value: three decimals, or ``<0.001`` when it underflows that."""
    if not _finite(x):
        return todo(tag)
    v = float(x)
    return "$<$0.001" if 0.0 <= v < 5e-4 else f"{v:.3f}"


