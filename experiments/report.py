    colspec = "l r r r"
    header = r"Feeder & Feeder-days & Held steps & Held rate (\%)"
    per: dict[str, dict[str, float]] = defaultdict(lambda: {"days": 0.0, "held": 0.0,
                                                            "steps": 0.0})
