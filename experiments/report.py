def tab_defense_decomposition(bank: Bank) -> str:
    schema = ("defense rung x model under the adaptive attacker; admission/FRR are "
              "measured at the fidelity+PBFT gate and read `--' on the rungs that "
              "have no gate, where 1.000/0.000 would be a definition rather than a "
              "measurement; the ledger column is `--' throughout because "
              "Ledger.verify() is not instrumented in the RunResults")
    colspec = "l l r r r r c"
    header = (r"Defense rung & Model & \macroF{} & $\Delta$ vs none & "
              r"Attacker adm. & Honest FRR & Ledger")
    base = {m: bank.f1(block="t1b", arm="no_defense", model=m, attack="adaptive_cosine")
            for m in ("cnn_lstm", "snn", "ssm")}
    body: list[str] = []
    for i, (label, block, arm) in enumerate(_RUNGS):
        if i:
            body.append("\\midrule\n")
        for model in ("cnn_lstm", "snn", "ssm"):
            rows = bank.select(block=block, arm=arm, model=model, attack="adaptive_cosine")
            vals = [float(r.macro_f1) for r in rows if _finite(r.macro_f1)]
            planned = PLANNED_SEEDS.get(block, 5)
            if arm == "no_defense":
                delta = NA  # this row *is* the reference, not a measured difference
            elif vals and base[model]:
                delta = _signs(f"{np.mean(vals) - np.mean(base[model]):+.3f}")
            else:
                delta = todo(f"delta {arm} {model}")
            gates = [g for g in (r.gate_stats() for r in rows) if g]
            # An arm with no admission gate admits everything and rejects nothing
            # *by definition*: 1.000 / 0.000 there is the arm's specification, not
            # a measurement, and printing it invites the reader to compare it with
            # the measured rates on the gated rungs. Structurally inapplicable, so
            # `--', exactly like the ledger column.
            has_gate = any(r.has_gate for r in rows) or arm in ("pipeline_krum",
                                                                "pipeline_geomed",
                                                                "fidelity_only")
            if not has_gate:
                adm = frr = NA
            else:
                adm = (mean_only([g["attacker_admission"] for g in gates],
                                 planned=planned, tag=f"adm {arm} {model}") if gates
                       else todo(f"adm {arm} {model}"))
                frr = (mean_only([g["honest_frr"] for g in gates], planned=planned,
                                 tag=f"frr {arm} {model}") if gates
                       else todo(f"frr {arm} {model}"))
            # The hash-chained ledger is built by the PBFT (pipeline) arms, but no
            # RunResult records a `Ledger.verify()` outcome, so there is nothing
            # here to tick: a \checkmark would assert an end-to-end verification
            # this battery never ran. The chain's integrity is covered by the
            # property tests, not by these runs.
            ledger = NA
            body.append(_r(label if model == "cnn_lstm" else "", MODEL_LABEL[model],
                           mean_sd(vals, planned=planned, tag=f"{arm} {model} adaptive"),
                           delta, adm, frr, ledger))
    note = (r"\vspace{2pt}\par\noindent{\footnotesize Attacker admission and honest "
            r"FRR are measured from the per-round \texttt{consensus.rejected} "
            r"partition, so they exist only on the rungs that run an admission "
            r"gate (fidelity-only and the two pipelines); on the ungated rungs "
            r"they read `--' because full admission and zero rejection are those "
            r"arms' definition rather than an observation. The ledger column is "
            r"`--' for every rung: the pipeline arms do append each committed "
            r"round to a SHA-256 hash chain, but no RunResult carries a "
            r"\texttt{Ledger.verify()} outcome, so this battery does not measure "
            r"end-to-end verification. Chain integrity and tamper-detection are "
            r"asserted by the property tests in \texttt{tests/}, not by these runs.}")
    return _table(schema, colspec, header, body, tail=note)


