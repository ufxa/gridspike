def _power_note(stats: dict[str, Any]) -> str:
    """The families whose Holm floor already exceeds 0.05 before any data lands."""
    families = [
        power_ceiling(stats["h2_wilcoxon"]),
        power_ceiling(stats["h3"]["evasion"]),
        power_ceiling(stats["h3"]["damage"]),
        power_ceiling(stats["h5"]["differential"]),
    ]
    blocked = [c for c in families if c and not c["decidable"]]
    if not blocked:
        return ""
    items = "; ".join(_ceiling_phrase(c) for c in blocked)
    return (r"\vspace{2pt}\par\noindent{\footnotesize \textbf{Power ceiling.} The "
            r"exact one-sided Wilcoxon signed-rank test on $n$ paired seeds cannot "
            r"return $p<2^{-n}$, and Holm within a family of $m$ members multiplies "
            r"the smallest $p$ by $m$; a family whose floor $m\cdot2^{-n}$ already "
            r"exceeds $0.05$ therefore cannot declare a single cell significant "
            r"whatever the data show. That is the case here for "
            + items + r". Those \emph{not supported} verdicts report the seed "
            r"budget of the pre-registered design, not a defense that failed: the "
            r"per-cell effect sizes and paired differences in "
            r"Table~\ref{tab:stats} and \texttt{runs/summary.json} carry the "
            r"evidence the family test cannot resolve.}")


def _family(rows: list[StatRow], unit: str, key: str) -> tuple[str, bool | None]:
    """Conjunctive family verdict: False as soon as one decided cell fails.

    A family whose rule is "holds in every cell" is *false* the moment one decided
    cell fails, however many cells are still missing -- but it can only be called
    *true* when every planned cell has been decided. Missing cells therefore never
    manufacture support, and never hide a refutation.

    The evidence string reads ``a/b support (b/c unit decided)``: the *numerator*
    is how many cells came out in the hypothesis's favour and the *denominator*
    is how many the runs could test at all. The older ``a/b cells decided (c
    planned)`` wording read as if ``b`` cells were undecided, which inverted the
    sense of the only number in the string that mattered.

    A power-limited family appends ``; family undecidable at this seed budget,
    floor p_Holm >= f`` *inside* that parenthesis, giving ``a/b support (b/c unit
    decided; family undecidable at this seed budget, floor p_Holm >= f)``. The
    clause is gated on the family's own Holm floor (:func:`power_ceiling`), so it
    only appears where no configuration of the data could have declared a cell
    significant. Without it the cell read ``24/24 cells decided`` beside prose
    calling the family undecidable, and the two senses of *decided* -- a cell
    returned a verdict, versus the family could be resolved at this ``n`` --
    looked like a contradiction. Both are true, and the string now says so.
    """
    decided = [r for r in rows if r.supported is not None]
    if not decided:
        return (todo(f"{key} evidence"), None)
    n_ok = sum(1 for r in decided if r.supported)
    ceiling = power_ceiling(rows)
    # Say it in the cell: no data could have supported this family at this n.
    limited = ceiling is not None and not ceiling["decidable"]
    floor = (f"; family undecidable at this seed budget, floor "
             f"$p_{{\\mathrm{{Holm}}}}\\ge{_tex_float(ceiling['holm_floor'])}$"
             if limited else "")
    evidence = (f"{n_ok}/{len(decided)} support "
                f"({len(decided)}/{len(rows)} {unit} decided{floor})")
    if n_ok < len(decided):
        return (evidence, False)
    return (evidence, True if len(decided) == len(rows) else None)


def _verdicts(stats: dict[str, Any]) -> dict[str, tuple[str, bool | None]]:
    """Evidence string + verdict per hypothesis; ``None`` = the data cannot decide."""
    out: dict[str, tuple[str, bool | None]] = {}
    h1a = stats["h1a"]
    if h1a["pooled"] and h1a["ci"]:
        ev = f"McNemar $p$ {_p(h1a['pooled']['p'])}, CI {ci_str(*h1a['ci'])}"
        out["H1a"] = (ev, bool(h1a["pooled"]["p"] > 0.05 and h1a["equivalent"]))
    else:
        out["H1a"] = (todo("H1a evidence"), None)
    h1b = stats["h1b"]
    if h1b["ci"]:
        out["H1b"] = (f"$\\rho$ CI {ci_str(*h1b['ci'], nd=4)}", bool(h1b["supported"]))
    else:
        out["H1b"] = (todo("H1b evidence"), None)
    out["H1"] = _conj(out["H1a"], out["H1b"], "H1a $\\wedge$ H1b")

    out["H2"] = _family(stats["h2_wilcoxon"], "cells", "H2")
    out["H3a"] = _family(stats["h3"]["evasion"], "cells", "H3a")
    out["H3b"] = _family(stats["h3"]["damage"], "cells", "H3b")
    geomed = [r for fam in ("evasion", "damage") for r in stats["h3"][fam]
              if "geo-median" in r.comparison]
    out["H3"] = _family(geomed, "geo-median cells", "H3")
    out["H4"] = _family(stats["h4"], "$\\tau$ curves", "H4")
    out["H5a"] = _family(stats["h5"]["trend"], "trends", "H5a")
    out["H5b"] = _family(stats["h5"]["differential"], "models", "H5b")
    out["H5"] = _conj(out["H5a"], out["H5b"], "H5a $\\wedge$ H5b")
    return out


def _conj(a: tuple[str, bool | None], b: tuple[str, bool | None],
          label: str) -> tuple[str, bool | None]:
    """Conjunction of two sub-verdicts: one refuted conjunct refutes the whole."""
    if a[1] is False or b[1] is False:
        return (label, False)
    if a[1] is None or b[1] is None:
        return (todo(label.replace("$\\wedge$", "and") + " evidence"), None)
    return (label, True)


